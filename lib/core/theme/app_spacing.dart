/// Vertical / screen rhythm used across Tasks, Dashboard, Settings.
abstract final class AppSpacing {
  /// Horizontal screen padding (list edges).
  static const double screen = 16;

  /// Gap between major dashboard / list sections.
  static const double section = 20;

  /// Gap under section titles.
  static const double sectionTitle = 10;

  /// Compact gap between related controls.
  static const double sm = 8;

  /// Medium gap inside cards / forms.
  static const double md = 12;

  /// Bottom padding for scroll views (nav bar clearance).
  static const double scrollBottom = 32;
}
